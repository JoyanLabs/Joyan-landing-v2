/**
 * Generate the *pinned* scene module: the snapshot with its private names also
 * exported, so the spike's reference model can reuse the scene's OWN hash, fbm,
 * dust tiers, halo table, envelopes, wander path and trail instead of restating
 * them (a restatement that drifts). The snapshot stays byte-identical to the
 * source, so its hash is usable provenance; this file is the derived artifact.
 *
 * Run: node design-studies/visual-directions/gpu-spike/make-pinned.mjs
 */
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';

const HERE = new URL('.', import.meta.url).pathname;
const SOURCE = resolve(HERE, 'scene-snapshot.mjs');
const OUT = resolve(HERE, 'scene-pinned.generated.mjs');

const PRIVATE = [
  'W', 'H', 'FPS', 'CYCLE', 'SECONDS', 'STOPS', 'TAIL_GAIN', 'EVENT', 'EASE',
  'eventEnvelope', 'WANDER', 'wanderAt', 'frac', 'bell', 'hash', 'vnoise', 'fbm',
  'DUST', 'dustTier', 'brightness', 'BRIGHT', 'HALO_REACH', 'haloTable', 'TAIL_S',
  'TAIL_P', 'COMA_R', 'BLINK_R', 'tailBox', 'TRAIL', 'trailRegion', 'trailTable',
  'cycleFrame',
];

const body = await readFile(SOURCE, 'utf8');
const sha = createHash('sha256').update(body).digest('hex');
const header = `/** GENERATED by make-pinned.mjs from scene-snapshot.mjs (sha256 ${sha}).\n *  The snapshot is the scene as it was when the GPU spike started; the private\n *  names below are re-exported so the spike's reference model reuses them. */\n`;
const out = `${header}${body}\nexport { ${PRIVATE.join(', ')} };\n`;
await writeFile(OUT, out);
console.log(`pinned ${OUT}\nsha256 ${sha}\nbytes ${out.length}`);
