/**
 * Build the constellation SCENE for the engine.
 *
 * Steps: read the drawing's polygons → take the convex hull plus the strongest
 * interior corners as the MAJOR nodes (12–16) → keep the hull as the links →
 * write a self-contained scene module whose field() draws, per cell: faint
 * dust, major stars with a slow twinkle, dotted links, and one pulse that
 * travels the link path. The engine renders it as dots; the animation comes
 * from the frame index, not from CSS.
 *
 * Output: lab/scene-constelacion.mjs (generated, deterministic).
 */
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const SRC = '/home/joshrm/Descargas/blade-runner-unicorn-line.svg';
const OUT = resolve(new URL('.', import.meta.url).pathname, 'scene-constelacion.mjs');

const svg = await readFile(SRC, 'utf8');
const polys = [...svg.matchAll(/<polygon[^>]*points="([^"]+)"/g)].map((m) =>
  m[1].trim().split(/\s+/).map((p) => p.split(',').map(Number)));

const all = polys.flat();
const cx = all.reduce((s, [x]) => s + x, 0) / all.length;
const cy = all.reduce((s, [, y]) => s + y, 0) / all.length;

/** Monotone chain convex hull. */
function hull(points) {
  const pts = [...points].sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  const cross = (o, a, b) => (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0]);
  const lower = [];
  for (const p of pts) {
    while (lower.length >= 2 && cross(lower[lower.length - 2], lower[lower.length - 1], p) <= 0) lower.pop();
    lower.push(p);
  }
  const upper = [];
  for (const p of [...pts].reverse()) {
    while (upper.length >= 2 && cross(upper[upper.length - 2], upper[upper.length - 1], p) <= 0) upper.pop();
    upper.push(p);
  }
  return lower.slice(0, -1).concat(upper.slice(0, -1));
}

const hullPts = hull(all);
// A convention hall: the hull plus up to four far-from-hull corners, chosen by
// distance to the centroid, so the figure keeps its character without becoming
// a mesh. Capped at 16 stars.
const extras = [...all]
  .filter((p) => !hullPts.some(([hx, hy]) => Math.hypot(hx - p[0], hy - p[1]) < 12))
  .sort((a, b) => Math.hypot(b[0] - cx, b[1] - cy) - Math.hypot(a[0] - cx, a[1] - cy))
  .slice(0, Math.max(0, 16 - hullPts.length));

const major = [...hullPts, ...extras];
const links = hullPts.map((p, i) => [p, hullPts[(i + 1) % hullPts.length]]);

// Normalise into 0..1, keeping the figure centred with air around it.
const xs = major.map(([x]) => x), ys = major.map(([, y]) => y);
const minX = Math.min(...xs), maxX = Math.max(...xs), minY = Math.min(...ys), maxY = Math.max(...ys);
const spanX = Math.max(1, maxX - minX), spanY = Math.max(1, maxY - minY);
const span = Math.max(spanX, spanY);
const norm = ([x, y]) => [
  0.5 + (x - (minX + maxX) / 2) / span * 0.86,
  0.5 + (y - (minY + maxY) / 2) / span * 0.86,
];
const NODES = major.map(norm).map(([x, y]) => [Number(x.toFixed(4)), Number(y.toFixed(4))]);
const LINKS = links.map(([a, b]) => [norm(a), norm(b)].map(([x, y]) => [Number(x.toFixed(4)), Number(y.toFixed(4))]));

await writeFile(OUT, `/**
 * GENERATED by build-scene-constelacion.mjs — do not edit by hand.
 *
 * The constellation of the drawing: ${NODES.length} major stars (convex hull + far corners)
 * and ${LINKS.length} links. Rendered by the engine as dots; the field animates the
 * twinkle and one travelling pulse.
 */
const W = 240;
const H = 150;
const FPS = 12;
const CYCLE = 96;            // 8 s
const SECONDS = CYCLE / FPS;

const STOPS = [
  '#0A1114', '#10191C', '#183039', '#244C5B', '#346E7B', '#4D9199',
  '#73B7B0', '#94CCBB', '#A8D3BA', '#D5E5CF', '#EAF3E6',
].map((hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255));

const NODES = ${JSON.stringify(NODES)};
const LINKS = ${JSON.stringify(LINKS)};

function toneColor(tone) {
  const s = Math.min(0.999, Math.max(0, tone)) * (STOPS.length - 1);
  const i = Math.floor(s), f = s - i;
  const a = STOPS[i], b = STOPS[Math.min(STOPS.length - 1, i + 1)];
  return [0, 1, 2].map((k) => a[k] + (b[k] - a[k]) * f);
}
const frac = (v) => v - Math.floor(v);
const bell = (d, s) => Math.exp(-(d * d) / (2 * s * s));
/** Deterministic dust: a hash, not a random call, so every frame agrees. */
const dust = (x, y) => frac(Math.sin(x * 12.9898 + y * 78.233) * 43758.5453);

function distToSegment(px, py, ax, ay, bx, by) {
  const vx = bx - ax, vy = by - ay;
  const t = Math.max(0, Math.min(1, ((px - ax) * vx + (py - ay) * vy) / (vx * vx + vy * vy || 1e-6)));
  return Math.hypot(px - (ax + vx * t), py - (ay + vy * t));
}

export function field(x, y, t) {
  const u = x / W, v = y / H;
  const p = t / SECONDS;
  let tone = 0.02 + 0.03 * (1 - v);                       // night air

  // 1 · dust: sparse, faint, static.
  const d = dust(x, y);
  if (d > 0.988) tone += 0.10 + 0.10 * d;

  // 2 · major stars with a slow twinkle, each on its own phase.
  NODES.forEach(([nx, ny], i) => {
    const tw = 0.75 + 0.25 * Math.sin((p * 2 + i * 0.37) * Math.PI * 2);
    tone += 0.95 * tw * bell(Math.hypot(u - nx, v - ny), 0.011);
    tone += 0.28 * bell(Math.hypot(u - nx, v - ny), 0.028);   // halo
  });

  // 3 · links: dotted, so they read as a sky chart and not as a wireframe.
  for (const [[ax, ay], [bx, by]] of LINKS) {
    const dist = distToSegment(u, v, ax, ay, bx, by);
    if (dist < 0.006) {
      const along = Math.hypot(u - ax, v - ay) / (Math.hypot(bx - ax, by - ay) || 1e-6);
      const dotPhase = frac(along * 34);                       // the dots
      if (dotPhase < 0.45) tone += 0.16 * (1 - dist / 0.006);
    }
  }

  // 4 · one pulse travelling the hull, so the figure has a heartbeat.
  const leg = Math.min(LINKS.length - 1, Math.floor(frac(p) * LINKS.length));
  const [[ax, ay], [bx, by]] = LINKS[leg];
  const head = frac(p * LINKS.length);
  const hx = ax + (bx - ax) * head, hy = ay + (by - ay) * head;
  tone += 0.75 * bell(Math.hypot(u - hx, v - hy), 0.013);

  return toneColor(tone);
}

export const constelacionScene = {
  id: 'lab-constelacion',
  label: 'constelación — nodos mayores',
  cols: W, rows: H, fps: FPS, cycleFrames: CYCLE, posterFrame: 12,
  palette: STOPS.map((c) => '#' + c.map((n) => Math.round(n * 255).toString(16).padStart(2, '0')).join('').toUpperCase()),
  ground: 0,
  groundHex: '#0A1114',
  params: { nodes: NODES.length, links: LINKS.length, seconds: SECONDS, resolution: W + ' × ' + H },
  field,
};

export default constelacionScene;
`);

console.log(`escena generada: ${NODES.length} estrellas, ${LINKS.length} enlaces → ${OUT}`);
